#!/usr/bin/env python3
"""Generate QuickRoute/Data/CurrencyPOIs.lua from client map tables.

Some places that take a currency are not merchants: the Trading Post opens
its own window, so a merchant visit never records it, and the AllTheThings
catalogue names the Trading Post's costs but no position. The client's
AreaPOI table holds each such place with a world position. This script
projects that position onto the UI map named in SPEC, through the
UiMapAssignment row of that map which contains the point.

Inputs are wago.tools CSV exports of one build:
  https://wago.tools/db2/AreaPOI/csv
  https://wago.tools/db2/UiMapAssignment/csv
  https://wago.tools/db2/UiMap/csv

Usage:
  generate_currency_pois.py --build 12.1.5.70783 --dir <csv dir> [--output <file>]
"""
import argparse
import csv
import pathlib

# (areaPoiID, uiMapID, faction, currencyID, name key)
# The UI map is named here because region boxes of neighbouring zones overlap.
SPEC = [
    (7396, 84, "Alliance", 2032, "TRADING_POST"),   # T&W Trading Post, Stormwind City
    (7397, 85, "Horde", 2032, "TRADING_POST"),      # Zen'shiri Trading Post, Orgrimmar
    (7791, 2339, "both", 2032, "TRADING_POST"),     # Trading Post, Dornogal
    (8616, 2393, "both", 2032, "TRADING_POST"),     # Trading Post, Silvermoon City
]


def read(path):
    with open(path, encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def project(poi, assignments, ui_map_id):
    x, y, z = (float(poi["Pos_%d" % i]) for i in range(3))
    for row in assignments:
        if row["UiMapID"] != str(ui_map_id) or row["MapID"] != poi["ContinentID"]:
            continue
        if row["WMOGroupID"] != "0" or row["WMODoodadPlacementID"] != "0":
            continue
        x0, y0, z0, x1, y1, z1 = (float(row["Region_%d" % i]) for i in range(6))
        if not (x0 <= x <= x1 and y0 <= y <= y1 and z0 <= z <= z1):
            continue
        u0, v0 = float(row["UiMin_0"]), float(row["UiMin_1"])
        u1, v1 = float(row["UiMax_0"]), float(row["UiMax_1"])
        # World x points north and world y west; map x runs east, map y south.
        return (round(u0 + (y1 - y) / (y1 - y0) * (u1 - u0), 4),
                round(v0 + (x1 - x) / (x1 - x0) * (v1 - v0), 4))
    raise ValueError("AreaPOI %s is outside every region of UI map %s" % (poi["ID"], ui_map_id))


def generate(build, directory):
    directory = pathlib.Path(directory)
    pois = {row["ID"]: row for row in read(directory / "AreaPOI.csv")}
    assignments = read(directory / "UiMapAssignment.csv")
    maps = {row["ID"]: row for row in read(directory / "UiMap.csv")}
    lines = [
        "-- CurrencyPOIs.lua -- generated by scripts/generate_currency_pois.py; do not edit.",
        "-- Places that take a currency but are not merchants, from the client tables",
        "-- AreaPOI, UiMapAssignment and UiMap of build %s (wago.tools CSV exports)." % build,
        "local ADDON_NAME, QR = ...",
        "",
        "QR.CurrencyPOIs = {",
    ]
    for poi_id, ui_map_id, faction, currency_id, name_key in SPEC:
        poi = pois.get(str(poi_id))
        if poi is None:
            raise ValueError("AreaPOI %d is missing from build %s" % (poi_id, build))
        x, y = project(poi, assignments, ui_map_id)
        lines.append('    { areaPoiID = %d, currencyID = %d, nameKey = "%s", mapID = %d, x = %s, y = %s, '
                     'faction = "%s" }, -- %s, %s' % (poi_id, currency_id, name_key, ui_map_id, x, y, faction,
                                                      poi["Name_lang"], maps[str(ui_map_id)]["Name_lang"]))
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--build", required=True)
    parser.add_argument("--dir", required=True)
    parser.add_argument("--output", default=str(pathlib.Path(__file__).resolve().parent.parent
                                                / "QuickRoute/Data/CurrencyPOIs.lua"))
    args = parser.parse_args()
    pathlib.Path(args.output).write_text(generate(args.build, args.dir), encoding="utf-8")


if __name__ == "__main__":
    main()
